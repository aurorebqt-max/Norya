'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { inspect, digest } = require('./import.cjs');
function compile(root, activate = false) {
  const result = inspect(root);
  if (result.errors.length) throw new Error(result.errors.join('\n'));
  const lessons = [], cards = [];
  for (const chapter of result.chapters) {
    const number = chapter.chapterId.slice(-2);
    const coverage = JSON.parse(fs.readFileSync(path.join(root, `contenus-norya/controle/kumar-${number}.couverture.json`), 'utf8'));
    const revision = JSON.parse(fs.readFileSync(path.join(root, `contenus-norya/kumar-${number}.revision.json`), 'utf8'));
    const expectedPages = chapter.pages.flatMap(([a,b]) => Array.from({length:b-a+1}, (_,i) => a+i));
    if (coverage.courseSha256 !== chapter.source.sha256 || revision.courseSha256 !== chapter.source.sha256) throw new Error(`${number}: couverture ou révisions périmées`);
    if (JSON.stringify(coverage.pages.map(p => p.printedPage)) !== JSON.stringify(expectedPages)) throw new Error(`${number}: couverture de pages incomplète ou hors périmètre`);
    const sections = chapter.sections.filter(s => s.kind === 'course');
    if (coverage.pages.some(p => p.pdfPage !== p.printedPage + 23 || !p.textExtracted || !sections.some(s => s.id === p.sectionId && s.pages.includes(p.printedPage)))) throw new Error(`${number}: traçabilité source invalide`);
    for (const item of [...revision.sheets, ...revision.flashcards]) {
      if (!sections.some(s => s.id === item.sectionId && s.pages.includes(item.page))) throw new Error(`${number}: support sans source`);
    }
    if (new Set(revision.sheets.map(s => s.sectionId)).size !== sections.length || new Set(revision.flashcards.map(c => c.id)).size !== revision.flashcards.length) throw new Error(`${number}: supports incomplets/doublons`);
    if (activate && (
      manifestChapter(root, chapter.chapterId).verification?.status !== 'beta'
      || sections.some(section => section.status !== 'beta')
      || revision.status !== 'beta'
      || revision.humanMedicalValidation !== false
      || revision.sheets.some(sheet => sheet.status !== 'beta')
      || revision.flashcards.some(card => card.status !== 'beta')
      || coverage.pages.some(page => page.openIssues.length && !/De verificat|À vérifier|Neclaritate|Contradicție|Divergență/u.test(sections.find(section => section.id === page.sectionId)?.markdown ?? ''))
    )) throw new Error(`${number}: activation bêta bloquée — couverture, supports ou avertissements incomplets`);
    const beta = activate;
    const bilingual = ro => ({ro, fr:''});
    const studentSections = chapter.sections.filter(section => ['course','sheet'].includes(section.kind));
    lessons.push({
      id:`norya-${chapter.chapterId}-markdown`, chapterId:chapter.chapterId, version:`md-${chapter.source.sha256}`, updatedOn:'2026-10-12',
      verification:beta ? 'beta' : 'needs-review', coverage:beta ? 'beta-documented-with-open-issues' : 'documented-with-open-issues', format:'markdown', rawMarkdown:chapter.rawMarkdown,
      title:bilingual(chapter.rawMarkdown.split('\n')[0].replace(/^# /,'')),
      status:beta
        ? 'Versiune beta — verificare în curs. Conținut documentat după paginile Kumar indicate; nu este validat medical integral. Punctele incerte sunt marcate „De verificat”. Recomandările terapeutice reflectă ediția 2021 și nu trebuie utilizate ca recomandări clinice actuale.'
        : 'Curs documentat pe întregul interval Tematica; relectură automată, fără validare medicală umană. Neclaritățile sursei sunt semnalate. Fiches/flashcards: repere provizorii, nu protocoale clinice.',
      sections:studentSections.map(s => ({id:s.id, title:bilingual(s.title.replace(/^#+ /,'')), text:bilingual(s.markdown), express:bilingual(s.kind === 'course' ? revision.sheets.find(f => f.sectionId === s.id)?.text || '' : revision.notice), pages:s.pages.join(', '), sourcePdfPages:s.pages.map(p => p+23).join(', ')})),
      questions:[],
    });
    for (const card of revision.flashcards) cards.push({id:card.id,sectionId:card.sectionId,objectiveId:chapter.chapterId,itemNumber:Number(number),subject:`Kumar · fișă ${beta ? 'beta' : 'documentară'}`,recto:card.question,verso:card.answer,sourceVersionId:`md-${chapter.source.sha256}`,explanation:`Kumar RO 2021, p. ${card.page}; ${card.sectionId}. ${beta ? 'Versiune beta — verificare în curs; răspuns bazat pe secțiunea documentată, fără doze litigioase.' : 'Relectură automată, fără validare medicală umană.'}`});
  }
  function manifestChapter(root, chapterId) {
    const manifest = JSON.parse(fs.readFileSync(path.join(root, 'contenus-norya/import-manifest.json'), 'utf8'));
    const chapter = manifest.chapters.find(item => item.chapterId === chapterId);
    if (!chapter) throw new Error(`${chapterId}: entrée de manifeste absente`);
    return chapter;
  }
  return '// Generated by scripts/content-import/compile.cjs. Edit Markdown sources, never this file.\n'
    + 'import type { RomanianLesson } from "./romanianLessons";\nimport type { Flashcard } from "../domain/medical/types";\n'
    + `export const importedKumarEnabled: boolean = ${activate};\n`
    + `export const importedKumarLessons: RomanianLesson[] = ${JSON.stringify(lessons,null,2)};\n`
    + `export const importedKumarCards: Flashcard[] = ${JSON.stringify(cards,null,2)};\n`;
}
module.exports = { compile };
if (require.main === module) {
  try {
    const args=process.argv.slice(2);
    if(args.some(a=>!['--check','--activate'].includes(a)))throw new Error('Options: --check, --activate');
    const root=path.resolve(__dirname,'../..');
    const file=path.join(root,'src/data/importedKumar.ts');
    const output=compile(root,args.includes('--activate'));
    if(args.includes('--check')) { if(fs.readFileSync(file,'utf8')!==output)throw new Error('Import généré périmé'); }
    else fs.writeFileSync(file,output);
    console.log('Import sans perte contrôlé. Version publiée: '+(args.includes('--activate')?'beta':'désactivée'));
  } catch(error) { console.error(error.message); process.exitCode=1; }
}
